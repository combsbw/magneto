#!/usr/bin/env python3
"""Build docs/ for GitHub Pages: the control app as an installable offline web app.

ui/app.html is a fragment. This wraps it the same way the board does (no Google Fonts; the CSS
already falls back to system fonts, which is what the soft AP serves) and adds a service worker
so an iPhone home-screen icon keeps working while joined to the device's own offline Wi-Fi.
"""
import hashlib
import os
import re
import shutil
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "ui", "app.html")
docs = os.path.join(root, "docs")
html = open(src, encoding="utf-8").read()

m = re.search(r"<style>.*?</style>", html, re.S)
if not m:
    sys.exit("build_pages: no <style> block found in ui/app.html")
style = m.group(0)
body = html[m.end():].strip()
if "<script>" not in body or 'class="app"' not in body:
    sys.exit("build_pages: ui/app.html does not look like the Magneto page")

page = (
    "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">"
    "<meta name=\"theme-color\" content=\"#0e1116\"><title>Magneto</title>"
    "<link rel=\"apple-touch-icon\" href=\"apple-touch-icon.png\">"
    "<link rel=\"icon\" type=\"image/png\" href=\"icon-192.png\">"
    "<link rel=\"manifest\" href=\"manifest.webmanifest\">"
    "<meta name=\"apple-mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"apple-mobile-web-app-title\" content=\"Magneto\">"
    "<meta name=\"apple-mobile-web-app-status-bar-style\" content=\"black\">"
    + style
    + "</head><body>"
    + body
    + "<script>if('serviceWorker' in navigator){"
    "navigator.serviceWorker.register('sw.js').catch(function(){});}"
    "</script></body></html>\n"
)

manifest = (
    '{"name":"Magneto","short_name":"Magneto","start_url":"./","scope":"./",'
    '"display":"standalone","orientation":"any","background_color":"#0e1116","theme_color":"#0e1116",'
    '"icons":[{"src":"icon-192.png","sizes":"192x192","type":"image/png","purpose":"any"},'
    '{"src":"apple-touch-icon.png","sizes":"180x180","type":"image/png","purpose":"any"}]}\n'
)

os.makedirs(docs, exist_ok=True)
open(os.path.join(docs, "index.html"), "w", encoding="utf-8").write(page)
open(os.path.join(docs, "manifest.webmanifest"), "w", encoding="utf-8").write(manifest)
open(os.path.join(docs, ".nojekyll"), "w").write("")
for name in ("apple-touch-icon.png", "icon-192.png"):
    shutil.copyfile(os.path.join(root, "icons", name), os.path.join(docs, name))

digest = hashlib.sha256()
for name in ("index.html", "manifest.webmanifest", "apple-touch-icon.png", "icon-192.png"):
    digest.update(open(os.path.join(docs, name), "rb").read())
cache = "magneto-" + digest.hexdigest()[:12]

sw = """/* Generated by tools/build_pages.py. Cache name changes when the page or icons change. */
var CACHE = '%s';
var SHELL = ['./index.html', './manifest.webmanifest', './apple-touch-icon.png', './icon-192.png'];

self.addEventListener('install', function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) { return cache.addAll(SHELL); }).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

self.addEventListener('fetch', function (event) {
  if (event.request.method !== 'GET') return;
  var url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(caches.match(event.request, {ignoreSearch: true}).then(function (hit) {
    var net = fetch(event.request).then(function (res) {
      if (res && res.ok) {
        var copy = res.clone();
        caches.open(CACHE).then(function (cache) { cache.put(event.request, copy); });
      }
      return res;
    }).catch(function () { return hit || caches.match('./index.html'); });
    return hit || net;
  }));
});
""" % cache

open(os.path.join(docs, "sw.js"), "w", encoding="utf-8").write(sw)
print("docs/: offline app, cache %s" % cache)
