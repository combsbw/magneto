#!/usr/bin/env python3
"""Build docs/ for GitHub Pages: the control app as an installable offline web app.

ui/app.html is a fragment. This wraps it the same way the board does (no Google Fonts; the CSS
already falls back to system fonts, which is what the soft AP serves) and adds a service worker
so an iPhone home-screen icon keeps working while joined to the device's own offline Wi-Fi.
"""
import hashlib
import os
import re
import shutil
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "ui", "app.html")
docs = os.path.join(root, "docs")
html = open(src, encoding="utf-8").read()

m = re.search(r"<style>.*?</style>", html, re.S)
if not m:
    sys.exit("build_pages: no <style> block found in ui/app.html")
style = m.group(0)
body = html[m.end():].strip()
if "<script>" not in body or 'class="app"' not in body:
    sys.exit("build_pages: ui/app.html does not look like the Magneto page")

page = (
    "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">"
    "<meta name=\"theme-color\" content=\"#0e1116\"><title>Magneto</title>"
    "<link rel=\"apple-touch-icon\" href=\"apple-touch-icon.png\">"
    "<link rel=\"icon\" type=\"image/png\" href=\"icon-192.png\">"
    "<link rel=\"manifest\" href=\"manifest.webmanifest\">"
    "<meta name=\"apple-mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"apple-mobile-web-app-title\" content=\"Magneto\">"
    "<meta name=\"apple-mobile-web-app-status-bar-style\" content=\"black\">"
    + style
    + "</head><body>"
    + body
    + "<script>if('serviceWorker' in navigator){"
    "navigator.serviceWorker.register('sw.js').catch(function(){});}"
    "</script></body></html>\n"
)

manifest = (
    '{"name":"Magneto","short_name":"Magneto","start_url":"./","scope":"./",'
    '"display":"standalone","orientation":"any","background_color":"#0e1116","theme_color":"#0e1116",'
    '"icons":[{"src":"icon-192.png","sizes":"192x192","type":"image/png","purpose":"any"},'
    '{"src":"apple-touch-icon.png","sizes":"180x180","type":"image/png","purpose":"any"}]}\n'
)

os.makedirs(docs, exist_ok=True)
open(os.path.join(docs, "index.html"), "w", encoding="utf-8").write(page)
open(os.path.join(docs, "manifest.webmanifest"), "w", encoding="utf-8").write(manifest)
open(os.path.join(docs, ".nojekyll"), "w").write("")
for name in ("apple-touch-icon.png", "icon-192.png"):
    shutil.copyfile(os.path.join(root, "icons", name), os.path.join(docs, name))

digest = hashlib.sha256()
for name in ("index.html", "manifest.webmanifest", "apple-touch-icon.png", "icon-192.png"):
    digest.update(open(os.path.join(docs, name), "rb").read())
cache = "magneto-" + digest.hexdigest()[:12]

# The page itself is fetched network-first so a new build shows up the launch after it is published,
# not the one after that: cache-first served the stale page once while the new worker installed
# behind it, which reads as "the update did not take". Icons and the manifest stay cache-first -
# they are small, they change with the cache name, and there is no reason to wait on the network for
# them. Offline (on the device's own Wi-Fi, which has no internet) the page request fails or stalls
# and falls straight back to the cache, so the installed app still opens with no network at all.
sw = """/* Generated by tools/build_pages.py. Cache name changes when the page or icons change. */
var CACHE = '%s';
var SHELL = ['./index.html', './manifest.webmanifest', './apple-touch-icon.png', './icon-192.png'];
var NET_MS = 2500;            /* stop waiting for the network this long after asking */

self.addEventListener('install', function (event) {
  event.waitUntil(caches.open(CACHE).then(function (cache) { return cache.addAll(SHELL); }).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (event) {
  event.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});

function fromCache(req) {
  return caches.match(req, {ignoreSearch: true}).then(function (hit) { return hit || caches.match('./index.html'); });
}

function keep(req, res) {
  if (res && res.ok) {
    var copy = res.clone();
    caches.open(CACHE).then(function (cache) { cache.put(req, copy); });
  }
  return res;
}

/* the page: newest wins, but never wait longer than NET_MS before using the cached copy */
function pageFirst(req) {
  return new Promise(function (resolve) {
    var settled = false;
    var done = function (r) { if (!settled) { settled = true; resolve(r); } };
    var timer = setTimeout(function () { if (!settled) fromCache(req).then(done); }, NET_MS);
    fetch(req).then(function (res) {
      clearTimeout(timer);
      if (settled) { keep(req, res); return; }      /* too slow to be used, still worth storing */
      done(keep(req, res));
    }).catch(function () {
      clearTimeout(timer);
      fromCache(req).then(done);
    });
  });
}

self.addEventListener('fetch', function (event) {
  if (event.request.method !== 'GET') return;
  var url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  var wantsPage = event.request.mode === 'navigate' ||
    (event.request.headers.get('accept') || '').indexOf('text/html') >= 0 ||
    /\\/(index\\.html)?$/.test(url.pathname);
  if (wantsPage) { event.respondWith(pageFirst(event.request)); return; }
  event.respondWith(caches.match(event.request, {ignoreSearch: true}).then(function (hit) {
    return hit || fetch(event.request).then(function (res) { return keep(event.request, res); })
      .catch(function () { return fromCache(event.request); });
  }));
});
""" % cache

open(os.path.join(docs, "sw.js"), "w", encoding="utf-8").write(sw)
print("docs/: offline app, cache %s" % cache)
