#!/usr/bin/env python3
"""Write certwindow.h: the server certificate's validity, baked in at compile time.

The phone checks these dates. The board's clock is often wrong, so the dates come from the
build, not from the board. Apple rejects a TLS server certificate longer than 398 days.
The certificate authority stored on the board is much longer and is what the phone trusts,
so a later build can renew the server certificate without another install.
"""
import os
from datetime import datetime, timedelta, timezone

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
dst = os.path.join(root, "certwindow.h")
start = datetime.now(timezone.utc) - timedelta(days=1)
end = start + timedelta(days=390)

def stamp(d):
    return d.strftime("%Y%m%d%H%M%S")

with open(dst, "w", encoding="utf-8") as f:
    f.write("// certwindow.h - generated by tools/cert_window.py. Do not edit.\n")
    f.write("#pragma once\n")
    f.write("#define CERT_NOT_BEFORE \"%s\"\n" % stamp(start))
    f.write("#define CERT_NOT_AFTER \"%s\"\n" % stamp(end))
print("certwindow.h: %s .. %s" % (stamp(start), stamp(end)))
