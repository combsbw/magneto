#!/usr/bin/env python3
"""Turn ui/app.html into webui.h (a gzipped byte array the sketch serves at / and /app).

ui/app.html is the same page that is published as the Claude artifact: it starts with <title>, a <meta> and a Google
Fonts <link>, then one <style>, the markup and one <script>, with no <html>/<head>/<body>. The soft AP has no internet,
so the fonts link is dropped (the CSS already falls back to system fonts) and the page is wrapped in a normal document.
The board carries no icons, manifest or service worker: the installable app is the GitHub Pages copy (tools/build_pages.py).
"""
import gzip
import hashlib
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "ui", "app.html")
dst = os.path.join(root, "webui.h")

html = open(src, encoding="utf-8").read()

m = re.search(r"<style>.*?</style>", html, re.S)
if not m:
    sys.exit("embed_ui: no <style> block found in ui/app.html")
style = m.group(0)
body = html[m.end():].strip()
if "<script>" not in body or "class=\"app\"" not in body:
    sys.exit("embed_ui: ui/app.html does not look like the Magneto page")

page = (
    "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">"
    "<meta name=\"theme-color\" content=\"#0e1116\"><title>Magneto</title>"
    + style + "</head><body>" + body
    # Earlier firmware registered a service worker for this address. This build has none, so remove the old one and its cache.
    + "<script>try{if('serviceWorker' in navigator)navigator.serviceWorker.getRegistrations().then(function(r){r.forEach(function(x){x.unregister();});});"
    "if(window.caches)caches.keys().then(function(k){k.forEach(function(n){caches.delete(n);});});}catch(e){}</script></body></html>"
)

raw = page.encode("utf-8")
cache = "magneto-" + hashlib.sha256(raw).hexdigest()[:12]
gz = gzip.compress(raw, 9, mtime=0)

lines = []
for i in range(0, len(gz), 16):
    lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]))

with open(dst, "w") as f:
    f.write("// webui.h - generated by tools/embed_ui.py from ui/app.html. Do not edit.\n")
    f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("// %d bytes of HTML, %d bytes gzipped\n" % (len(raw), len(gz)))
    f.write("static const char WEBUI_CACHE_ID[] = \"%s\";\n" % cache)
    f.write("static const size_t WEBUI_GZ_LEN = %d;\n" % len(gz))
    f.write("static const uint8_t WEBUI_GZ[] PROGMEM = {\n" + ",\n".join(lines) + "\n};\n")

print("webui.h: %d bytes html -> %d bytes gzip" % (len(raw), len(gz)))
