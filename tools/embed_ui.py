#!/usr/bin/env python3
"""Turn ui/app.html into webui.h: the page, the icon and the manifest, all served by the board.

The board is the only host now - there is no GitHub Pages copy and no https - so everything "Add to
Home Screen" needs has to come out of flash: the gzipped page, a 192x192 PNG and a small manifest.
ui/app.html starts with <title>, a <meta> and a Google Fonts <link>, then one <style>, the markup
and one <script>, with no <html>/<head>/<body>. The soft AP has no internet, so the fonts link is
dropped (the CSS already falls back to system fonts) and the page is wrapped in a real document
with the icon and manifest links in its head.
"""
import gzip
import hashlib
import os
import re
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "ui", "app.html")
dst = os.path.join(root, "webui.h")

html = open(src, encoding="utf-8").read()

m = re.search(r"<style>.*?</style>", html, re.S)
if not m:
    sys.exit("embed_ui: no <style> block found in ui/app.html")
style = m.group(0)
body = html[m.end():].strip()
if "<script>" not in body or "class=\"app\"" not in body:
    sys.exit("embed_ui: ui/app.html does not look like the Magneto page")

page = (
    "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">"
    "<meta name=\"theme-color\" content=\"#0e1116\"><title>Magneto</title>"
    # Add to Home Screen, served by the board itself.
    "<link rel=\"manifest\" href=\"/manifest.webmanifest\">"
    "<link rel=\"apple-touch-icon\" href=\"/icon.png\">"
    "<link rel=\"icon\" type=\"image/png\" href=\"/icon.png\">"
    "<meta name=\"apple-mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"mobile-web-app-capable\" content=\"yes\">"
    "<meta name=\"apple-mobile-web-app-title\" content=\"Magneto\">"
    "<meta name=\"apple-mobile-web-app-status-bar-style\" content=\"black\">"
    + style + "</head><body>" + body
    # Earlier builds published this page on GitHub Pages with a service worker, and it may still be
    # registered on a phone that installed it from there. Clear it out so the board's own copy is
    # never shadowed by a stale cache.
    + "<script>try{if('serviceWorker' in navigator)navigator.serviceWorker.getRegistrations().then(function(r){r.forEach(function(x){x.unregister();});});"
    "if(window.caches)caches.keys().then(function(k){k.forEach(function(n){caches.delete(n);});});}catch(e){}</script></body></html>"
)

# start_url and scope are the board's root; it answers on 192.168.4.1 and magneto.local alike.
manifest = (
    '{"name":"Magneto","short_name":"Magneto","start_url":"/","scope":"/",'
    '"display":"standalone","orientation":"any","background_color":"#0e1116","theme_color":"#0e1116",'
    '"icons":[{"src":"/icon.png","sizes":"192x192","type":"image/png","purpose":"any"}]}'
)
icon = open(os.path.join(root, "icons", "icon-192.png"), "rb").read()

raw = page.encode("utf-8")
cache = "magneto-" + hashlib.sha256(raw).hexdigest()[:12]
gz = gzip.compress(raw, 9, mtime=0)

def c_array(name, data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 16]))
    return ("static const size_t %s_LEN = %d;\n" % (name, len(data))
            + "static const uint8_t %s[] PROGMEM = {\n" % name + ",\n".join(lines) + "\n};\n")


mgz = gzip.compress(manifest.encode("utf-8"), 9, mtime=0)

with open(dst, "w") as f:
    f.write("// webui.h - generated by tools/embed_ui.py from ui/app.html and icons/. Do not edit.\n")
    f.write("#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("// page: %d bytes of HTML, %d gzipped. icon: %d bytes. manifest: %d gzipped.\n"
            % (len(raw), len(gz), len(icon), len(mgz)))
    f.write("static const char WEBUI_CACHE_ID[] = \"%s\";\n" % cache)
    f.write(c_array("WEBUI_GZ", gz))
    f.write("\n// 192x192 PNG, already compressed; served as-is at /icon.png\n")
    f.write(c_array("WEBUI_ICON", icon))
    f.write("\n// /manifest.webmanifest, gzipped\n")
    f.write(c_array("WEBUI_MANIFEST_GZ", mgz))

print("webui.h: html %d -> %d gz, icon %d, manifest %d gz, total %d bytes in flash"
      % (len(raw), len(gz), len(icon), len(mgz), len(gz) + len(icon) + len(mgz)))
